const express = require("express");
const authenticate = require("../../core/middleware/auth.middleware");
const validate = require("../../core/middleware/validation.middleware");
const { upload, validateImageContent } = require("../../core/middleware/upload.middleware");
const { requireRoles } = require("../../core/middleware/authorization.middleware");
const controller = require("./event.controller");
const { ADMIN_ROLES } = require("./event.constants");
const { createEventSchema, updateEventSchema, eventQuerySchema, publicationSchema } = require("./event.validator");
const router = express.Router();
const optionalAuthenticate = (req, res, next) => req.headers.authorization ? authenticate(req, res, next) : next();
const validateUploadedImage = (req, res, next) => req.file ? validateImageContent(req, res, next) : next();
router.get("/", optionalAuthenticate, controller.list);
router.get("/:id", optionalAuthenticate, controller.getById);
router.use(authenticate, requireRoles(...ADMIN_ROLES));
router.post("/", upload.single("image"), validateUploadedImage, validate(createEventSchema), controller.create);
router.patch("/:id", upload.single("image"), validateUploadedImage, validate(updateEventSchema), controller.update);
router.patch("/:id/publication", validate(publicationSchema), controller.publish);
router.delete("/:id", controller.remove);
module.exports = router;
